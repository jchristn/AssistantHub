// Requires playwright-core (or set PLAYWRIGHT_MODULE to an installed module path)
// and a Vite dev server at TABLE_TEST_URL. Uses an installed Chrome browser.
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const browser = await chromium.launch({ executablePath: process.env.CHROME_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const url = process.env.TABLE_TEST_URL || 'http://127.0.0.1:15174/tests/fixtures/tableColumns.html';
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const table = id => page.locator(`[data-table-id="${id}"]`);
  const controls = id => page.locator(`[data-table-controls-for="${id}"]`);
  const menu = id => page.locator(`[data-column-options-for="${id}"]`);
  const open = async id => { const details = controls(id).locator('details'); if (await details.getAttribute('open') !== null) return; if (await page.locator('[data-table-controls-for] details[open]').count()) await page.keyboard.press('Escape'); await details.locator('summary').click(); };
  const visible = async id => table(id).locator('thead tr').first().locator('th:visible').allTextContents();
  await page.goto(url);
  await table('fixture-native').locator('summary').waitFor();
  await open('fixture-native');
  for (const name of ['Name Required', 'Status Required', 'Actions Required']) assert.ok(await menu('fixture-native').getByRole('checkbox', { name, exact: true }).isDisabled());
  await menu('fixture-native').getByRole('checkbox', { name: 'Metric', exact: true }).uncheck();
  assert.deepEqual(await visible('fixture-native'), ['Name', 'Status', 'Actions']);
  assert.deepEqual(await visible('fixture-independent'), ['Name', 'Metric']);
  await page.getByRole('button', { name: 'Add row', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[data-table-id="fixture-native"] tbody').rows.length === 2);
  assert.equal(await table('fixture-native').locator('tbody td:visible').count(), 6);
  await page.getByRole('button', { name: 'Change schema', exact: true }).click();
  assert.deepEqual(await visible('fixture-native'), ['Name', 'Status', 'New column', 'Actions']);
  await table('fixture-native').getByRole('button', { name: 'Row action' }).first().click();
  assert.equal(await page.locator('output').textContent(), '1 actions');
  await page.reload();
  await open('fixture-native');
  assert.deepEqual(await visible('fixture-native'), ['Name', 'Status', 'Actions']);
  await page.keyboard.press('Escape');
  assert.equal(await controls('fixture-native').locator('details').getAttribute('open'), null);
  await open('fixture-native');
  await menu('fixture-native').getByRole('button', { name: 'Show all columns' }).click();
  assert.deepEqual(await visible('fixture-native'), ['Name', 'Status', 'Metric', 'Actions']);
  const data = table('fixture-data');
  await data.locator('tbody tr').first().waitFor();
  const toolbar = page.locator('.data-table-toolbar').filter({ has: controls('fixture-data') });
  assert.equal(await toolbar.count(), 1, 'Columns is inside the pagination toolbar');
  assert.equal(await toolbar.locator('.pagination').count(), 1);
  assert.equal(await data.locator('.column-controls').count(), 0, 'no separate selector row above the table');
  const summaryBounds = await controls('fixture-data').locator('summary').boundingBox();
  const paginationBounds = await toolbar.locator('.pagination').boundingBox();
  assert.ok(Math.abs(summaryBounds.y + summaryBounds.height / 2 - paginationBounds.y - paginationBounds.height / 2) < 3, 'selector and pagination share a horizontal row');
  // The real endpoint table starts with operational fields and can reset after an override.
  await table('inferenceendpoints-list-1').locator('tbody tr').waitFor();
  assert.deepEqual(await visible('inferenceendpoints-list-1'), ['Id', 'Name', 'Model', 'ApiFormat', 'Active', 'Health']);
  await open('inferenceendpoints-list-1');
  await menu('inferenceendpoints-list-1').getByRole('button', { name: 'Show all columns', exact: true }).click();
  assert.equal((await visible('inferenceendpoints-list-1')).length, 8);
  await page.reload();
  await table('inferenceendpoints-list-1').locator('tbody tr').waitFor();
  assert.equal((await visible('inferenceendpoints-list-1')).length, 8, 'saved show-all overrides defaults');
  await open('inferenceendpoints-list-1');
  await menu('inferenceendpoints-list-1').getByRole('button', { name: 'Reset to defaults', exact: true }).click();
  assert.deepEqual(await visible('inferenceendpoints-list-1'), ['Id', 'Name', 'Model', 'ApiFormat', 'Active', 'Health']);
  await open('fixture-data');
  assert.ok(await menu('fixture-data').getByRole('checkbox', { name: 'Select rows Required', exact: true }).isDisabled());
  assert.ok(await menu('fixture-data').getByRole('checkbox', { name: 'Actions Required', exact: true }).isDisabled());
  assert.ok(await menu('fixture-data').getByRole('checkbox', { name: 'Audit Required', exact: true }).isDisabled());
  // Filters and sorting stay usable; hiding their column clears invisible constraints.
  await data.getByPlaceholder('Filter...').fill('Zulu');
  assert.equal(await data.locator('tbody tr').count(), 1);
  await open('fixture-data');
  await menu('fixture-data').getByRole('checkbox', { name: 'Name', exact: true }).uncheck();
  await page.waitForFunction(() => document.querySelector('[data-table-id="fixture-data"] tbody').rows.length === 2);
  assert.equal(await data.locator('thead input[placeholder="Filter..."]:visible').count(), 0);
  await menu('fixture-data').getByRole('checkbox', { name: 'Name', exact: true }).check();
  await data.getByPlaceholder('Filter...').fill('no match');
  await open('fixture-data');
  await menu('fixture-data').getByRole('checkbox', { name: 'Status', exact: true }).uncheck();
  assert.equal(await data.locator('tbody td').getAttribute('colspan'), '5');
  await menu('fixture-data').getByRole('button', { name: 'Show all columns' }).click();
  assert.equal(await data.locator('tbody td').getAttribute('colspan'), '6');
  await data.getByPlaceholder('Filter...').fill('');
  await data.locator('thead tr').first().getByText('Name', { exact: true }).click();
  assert.ok((await data.locator('tbody tr').first().textContent()).includes('two'));
  await open('fixture-data');
  await menu('fixture-data').getByRole('checkbox', { name: 'Name', exact: true }).uncheck();
  await page.waitForFunction(() => document.querySelector('[data-table-id="fixture-data"] tbody tr')?.textContent.includes('one'));
  await data.locator('tbody input[type="checkbox"]').first().check();
  assert.equal(await page.getByRole('button', { name: 'Delete Selected (1)', exact: true }).count(), 1);
  await data.locator('tbody .action-menu-trigger').first().click();
  await page.getByText('Example action', { exact: true }).click();
  assert.equal(await page.locator('output').textContent(), '0 actions');
  await data.locator('tbody tr').first().locator('td').nth(1).click();
  assert.equal(await page.locator('output').textContent(), '1 actions');
  await page.getByRole('button', { name: 'Open table dialog', exact: true }).click();
  await open('fixture-dialog');
  await menu('fixture-dialog').getByRole('checkbox', { name: 'Metric', exact: true }).uncheck();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.modal-overlay').count(), 1);
  assert.equal(await controls('fixture-dialog').locator('details').getAttribute('open'), null);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.modal-overlay').count(), 0);
  await open('fixture-markdown');
  await menu('fixture-markdown').getByRole('checkbox', { name: 'Description', exact: true }).uncheck();
  assert.deepEqual(await visible('fixture-markdown'), ['Item']);
  // Tampering with saved required columns must not remove them on reload.
  await page.evaluate(() => localStorage.setItem('assistanthub.table.columns.fixture-native', JSON.stringify(['Name', 'Status', '__actions', 'Metric'])));
  await page.reload();
  await open('fixture-native');
  assert.deepEqual(await visible('fixture-native'), ['Name', 'Status', 'Actions']);
  await page.screenshot({ path: '/tmp/assistanthub-columns-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await open('fixture-data');
  const mobileControls = await controls('fixture-data').locator('summary').boundingBox();
  assert.ok(mobileControls.x >= 0 && mobileControls.x + mobileControls.width <= 390, 'toolbar selector fits the narrow viewport');
  const popup = await menu('fixture-data').boundingBox();
  assert.ok(popup.x >= 0 && popup.x + popup.width <= 390 && popup.y >= 0 && popup.y + popup.height <= 844, 'dropdown stays inside the viewport');
  await page.screenshot({ path: '/tmp/assistanthub-columns-mobile.png' , fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS column toggles, required columns, table isolation, persistence, schema/row updates, actions, filters/sorting, spans, Markdown, keyboard, and tampered storage');
  const blocked = await browser.newPage();
  blocked.on('pageerror', error => errors.push(error.message));
  await blocked.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new Error('Blocked storage'); } }));
  await blocked.goto(url);
  const blockedTable = blocked.locator('[data-table-id="fixture-native"]');
  await blockedTable.locator('summary').click();
  await blocked.locator('[data-column-options-for="fixture-native"]').getByRole('checkbox', { name: 'Metric', exact: true }).uncheck();
  assert.equal(await blockedTable.locator('th:visible').count(), 3);
  assert.deepEqual(errors, []);
  console.log('PASS blocked browser storage');
} finally {
  await browser.close();
}
